namespace MPL.X4.TradeData.UI.Models.SpecialItem;

/// <summary>
/// An enumeration that defines the type of a special item.
/// </summary>
public enum SpecialItemType
{
    /// <summary>
    /// The special item type is unknown.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// The special item is a build storage.
    /// </summary>
    BuildStorage,

    /// <summary>
    /// The special item is a lockbox.
    /// </summary>
    Lockbox,

    /// <summary>
    /// The special item is a ship.
    /// </summary>
    Ship,

    /// <summary>
    /// The special item is an extra large ship.
    /// </summary>
    ShipExtraLarge,

    /// <summary>
    /// The special item is an extra small ship.
    /// </summary>
    ShipExtraSmall,

    /// <summary>
    /// The special item is a large ship.
    /// </summary>
    ShipLarge,

    /// <summary>
    /// The special item is a medium ship.
    /// </summary>
    ShipMedium,

    /// <summary>
    /// The special item is a small ship.
    /// </summary>
    ShipSmall
}
