    /// The ship class is unknown.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// The ship is extra large.
    /// </summary>
    ExtraLarge,

    /// <summary>
    /// The ship is large.
    /// </summary>
    Large,

    /// <summary>
    /// The ship is medium.
    /// </summary>
    Medium,

    /// <summary>
    /// The ship is small.
    /// </summary>
    Small
}
