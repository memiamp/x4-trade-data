namespace MPL.X4.SaveGame.Models;

/// <summary>
/// An enumeration that defines the class of a ship.
/// </summary>
public enum ShipClass
{
    /// <summary>
    /// The ship class is unknown.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// The ship class is extra large.
    /// </summary>
    ExtraLarge,

    /// <summary>
    /// The ship class is extra small.
    /// </summary>
    ExtraSmall,

    /// <summary>
    /// The ship class is large.
    /// </summary>
    Large,

    /// <summary>
    /// The ship class is medium.
    /// </summary>
    Medium,

    /// <summary>
    /// The ship class is small.
    /// </summary>
    Small
}
