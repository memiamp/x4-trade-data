namespace MPL.X4.SaveGame.Models;

/// <summary>
/// An enumeration that defines the ware rarity of a lockbox.
/// </summary>
public enum LockboxRarity
{
    /// <summary>
    /// The rarity is unknown.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// The lockbox wares are common rarity.
    /// </summary>
    Common,

    /// <summary>
    /// The lockbox wares are rare rarity.
    /// </summary>
    Rare,

    /// <summary>
    /// The lockbox wares are unusual rarity.
    /// </summary>
    Unusual
}
